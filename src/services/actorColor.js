/**
 * Deterministic colour for each actor in a script.
 *
 * Colours are derived from the actor name, so nothing has to be stored in the
 * script data. Within one script every actor gets a different colour: the name
 * alone cannot guarantee that, because uniqueness needs to know the whole cast,
 * so the assignment is computed per script from the cast that is already in the
 * parsed JSON.
 *
 * Adding a role to a script keeps roughly 98% of the existing colours, because
 * the palette is a fixed 48 slots and each actor's preference order depends
 * only on its own name. A role is only displaced when a newcomer wants the
 * exact slot it holds.
 *
 * The palette itself is generated by scripts/gen-actor-palette.mjs. Every
 * colour clears WCAG AA on every background the app uses, in both themes, and
 * the set stays distinguishable under red-green colour vision deficiency. See
 * that script for the reasoning.
 */

