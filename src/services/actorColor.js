const SLOTS = PALETTE.length;

/** True for the pseudo-actor that stands in for unattributed stage directions. */
function isStageDirections(actor) {
  return !actor || actor === 'undefined';
}

/** FNV-1a. Small, dependency free, and it avalanches: "Тевье" and "Тевья" land far apart. */
function hash(text, seed) {
  let h = seed >>> 0;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/**
 * The order this actor would like to claim palette slots in.
 * Derived only from the name, so it never shifts when the cast changes.
 */
function preferences(actor) {
  let state = hash(actor, 0x811c9dc5) || 1;
  const random = () => {
    // xorshift32, seeded from the name
    state ^= state << 13; state >>>= 0;
    state ^= state >> 17;
    state ^= state << 5; state >>>= 0;
    return state / 0x100000000;
  };
  const order = Array.from({ length: SLOTS }, (_, i) => i);
  for (let i = SLOTS - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}

/**
 * Give every actor its own palette slot.
 *
 * Actors are processed in hash order rather than alphabetically or by line
 * count, both of which would reshuffle when the script is edited. Each takes
 * the first slot it prefers that is still free.
 *
 * Casts larger than the palette are not realistic today (the largest script has
 * 41 actors) but are handled by letting the overflow share colours rather than
 * throwing.
 */
export function assignActorColors(actors) {
  const cast = actors.filter(a => !isStageDirections(a));
  const order = [...cast].sort((a, b) => hash(a, 7) - hash(b, 7) || (a < b ? -1 : 1));

  const taken = new Array(SLOTS).fill(false);
  const colors = {};

  for (const actor of order) {
    const wanted = preferences(actor);
    let slot = wanted.find(i => !taken[i]);
    if (slot === undefined) slot = wanted[0]; // cast exceeds the palette
    taken[slot] = true;
    colors[actor] = { light: PALETTE[slot][0], dark: PALETTE[slot][1] };
  }

  return colors;
}

/** Every distinct actor in a parsed script, stage directions excluded. */
export function castOf(script) {
  const cast = new Set();
  for (const act of script?.acts || []) {
    for (const scene of act.scenes || []) {
      for (const line of scene.lines || []) {
        if (!isStageDirections(line.actor)) cast.add(line.actor);
      }
    }
  }
  return [...cast];
}

const cache = new Map();

/**
 * Colours for a whole script, memoised.
 *
 * The largest script renders several thousand lines, so this must not be
 * recomputed per line. Keyed on the cast so an edited script recolours.
 */
export function actorColorsForScript(script) {
  const cast = castOf(script);
  if (cast.length === 0) return {};
  const key = [...cast].sort().join('\u0000');
  let colors = cache.get(key);
  if (!colors) {
    colors = assignActorColors(cast);
    cache.set(key, colors);
  }
  return colors;
}
